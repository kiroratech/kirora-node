/**
 * Removes the operations not in OPERATIONS, then every component nothing still uses. The
 * error codes and webhook names are read before this, from the whole spec.
 */
function prune(spec) {
  const found = new Set();
  for (const [path, item] of Object.entries(spec.paths)) {
    for (const [method, operation] of Object.entries(item)) {
      if (!operation?.operationId) continue;
      if (OPERATIONS.includes(operation.operationId)) found.add(operation.operationId);
      else delete item[method];
    }
    if (!Object.values(item).some((operation) => operation?.operationId)) {
      delete spec.paths[path];
    }
  }
  const missing = OPERATIONS.filter((operationId) => !found.has(operationId));
  if (missing.length > 0) fail(`Not in the spec: ${missing.join(', ')}`);

  const used = new Set();
  const visit = (value) => {
    if (Array.isArray(value)) return value.forEach(visit);
    if (typeof value !== 'object' || value === null) return;
    if (typeof value.$ref === 'string' && !used.has(value.$ref)) {
      used.add(value.$ref);
      visit(deref(spec, value.$ref));
    }
    Object.values(value).forEach(visit);
  };
  visit(spec.paths);
  visit(spec.webhooks);
  // Also used by the client, which maps every error body onto it.
  visit({ $ref: '#/components/schemas/ErrorCode' });
  for (const [kind, components] of Object.entries(spec.components)) {
    for (const name of Object.keys(components)) {
      if (!used.has(`#/components/${kind}/${name}`)) delete components[name];
    }
  }
  return spec;
}

// Generate everything before writing anything, so a failure can't leave a mix of
// old and new files. `prune()` changes the spec, so the operations come first.
const operations = operationsFile(spec);
const models = astToString(await openapiTS(prune(spec), { defaultNonNullable: false }));
const outputs = new Map([
  ['../src/errors/error-codes.ts', constList('ERROR_CODES', errorCodes)],
  ['../src/webhooks/webhook-events.ts', constList('WEBHOOK_EVENTS', webhookEvents)],
  ['../src/models.ts', `${header}\n${models}`],
  ['../src/core/operations.ts', operations],
]);

if (check) {
  const stale = [...outputs]
    .filter(([path, content]) => {
      const url = new URL(path, import.meta.url);
      return !existsSync(url) || readFileSync(url, 'utf8') !== content;
    })
    .map(([path]) => path.replace('../', ''));
  if (stale.length > 0) {
    fail(`Out of date with ${specName}: ${stale.join(', ')}. Run \`pnpm codegen\`.`);
  }
  process.stdout.write('Generated files are up to date\n');
} else {
  for (const [path, content] of outputs) {
    writeFileSync(new URL(path, import.meta.url), content);
  }
  process.stdout.write(
    `Wrote ${errorCodes.length} error codes, ${webhookEvents.length} webhook events, the payload types and the retry table\n`,
  );
}
